# =============================================================================
# БАЗОВЫЙ КЛАСС ACTOR
# Описывает общие свойства всех движущихся объектов в игре:
# - позиция (x, y)
# - направление взгляда (facing)
# - путь движения (path)
# - счётчик застреваний (stuck_counter)
# - здоровье (health, max_health)
# - скорость движения (speed)
# - радиус восприятия (perception_radius)
# =============================================================================

class Actor:
    """
    Базовый класс для всех движущихся сущностей в игре.
    Наследники: Person (игрок, NPC), Animal (кошки, собаки, крысы и другие животные).
    """
    
    def __init__(self, actor_id, name, x, y):
        """
        Инициализация базового Actor.
        
        Аргументы:
            actor_id (str): Уникальный идентификатор сущности.
            name (str): Отображаемое имя.
            x (int): Начальная координата X на карте.
            y (int): Начальная координата Y на карте.
        """
        self.id = actor_id
        self.name = name
        self.x = x
        self.y = y
        
        # Направление взгляда (строка: "north", "south", "east", "west")
        # Используется для отрисовки линии взгляда и логики взаимодействия
        self.facing = "south"
        
        # Путь движения — список клеток [(x1, y1), (x2, y2), ...]
        # Пустой список означает, что сущность стоит на месте
        self.path = []
        
        # Счётчик застреваний — увеличивается, если сущность не может двигаться
        # Используется для принятия решения об обходе препятствий или сбросе пути
        self.stuck_counter = 0
        
        # -------------------------------------------------------------------------
        # ЗДОРОВЬЕ
        # -------------------------------------------------------------------------
        # Текущее здоровье (0 = мёртв)
        self.health = 100
        
        # Максимальное здоровье
        self.max_health = 100
        
        # -------------------------------------------------------------------------
        # СКОРОСТЬ И ВОСПРИЯТИЕ
        # -------------------------------------------------------------------------
        # Скорость движения (задержка между шагами в миллисекундах)
        # Чем меньше значение, тем быстрее движется сущность
        self.speed = 1000  # По умолчанию 1 шаг в секунду
        
        # Радиус восприятия (в клетках)
        # Используется для обнаружения других сущностей (игрок видит NPC, NPC видит игрока, животные чувствуют опасность)
        self.perception_radius = 5
        
        # Время последнего шага (для задержки движения)
        self.last_move_time = 0
    
    # -------------------------------------------------------------------------
    # МЕТОДЫ РАБОТЫ С ПОЗИЦИЕЙ
    # -------------------------------------------------------------------------
    
    def set_position(self, x, y):
        """
        Устанавливает позицию сущности.
        
        Аргументы:
            x (int): Новая координата X.
            y (int): Новая координата Y.
        """
        self.x = x
        self.y = y
    
    def is_at(self, x, y):
        """
        Проверяет, находится ли сущность в указанной клетке.
        
        Аргументы:
            x (int): Координата X для проверки.
            y (int): Координата Y для проверки.
        
        Возвращает:
            bool: True, если сущность в клетке (x, y).
        """
        return self.x == x and self.y == y
    
    def distance_to(self, other):
        """
        Вычисляет манхэттенское расстояние до другой сущности или клетки.
        
        Аргументы:
            other: Может быть:
                - Actor (другая сущность)
                - Кортеж (x, y)
                - Список [x, y]
        
        Возвращает:
            int: Манхэттенское расстояние (|x1-x2| + |y1-y2|).
        """
        if isinstance(other, Actor):
            target_x, target_y = other.x, other.y
        else:
            target_x, target_y = other[0], other[1]
        
        return abs(self.x - target_x) + abs(self.y - target_y)
    
    # -------------------------------------------------------------------------
    # МЕТОДЫ РАБОТЫ С НАПРАВЛЕНИЕМ
    # -------------------------------------------------------------------------
    
    def get_facing_delta(self):
        """
        Возвращает смещение (dx, dy) для текущего направления взгляда.
        
        Возвращает:
            tuple: (dx, dy) — смещение на одну клетку в направлении facing.
                   Например, для "north" вернёт (0, -1).
        """
        if self.facing == "north":
            return (0, -1)
        elif self.facing == "south":
            return (0, 1)
        elif self.facing == "east":
            return (1, 0)
        elif self.facing == "west":
            return (-1, 0)
        else:
            # По умолчанию смотрим на юг
            return (0, 1)
    
    def set_facing_from_delta(self, dx, dy):
        """
        Устанавливает направление взгляда на основе смещения.
        
        Аргументы:
            dx (int): Смещение по X (-1, 0, 1).
            dy (int): Смещение по Y (-1, 0, 1).
        """
        if dx == 0 and dy == -1:
            self.facing = "north"
        elif dx == 0 and dy == 1:
            self.facing = "south"
        elif dx == 1 and dy == 0:
            self.facing = "east"
        elif dx == -1 and dy == 0:
            self.facing = "west"
        # Если dx и dy оба 0 или диагональ — не меняем направление
    
    # -------------------------------------------------------------------------
    # МЕТОДЫ РАБОТЫ СО ЗДОРОВЬЕМ
    # -------------------------------------------------------------------------
    
    def take_damage(self, amount):
        """
        Наносит урон сущности.
        
        Аргументы:
            amount (int): Количество урона.
        """
        self.health = max(0, self.health - amount)
    
    def heal(self, amount):
        """
        Восстанавливает здоровье.
        
        Аргументы:
            amount (int): Количество восстановления.
        """
        self.health = min(self.max_health, self.health + amount)
    
    def is_alive(self):
        """
        Проверяет, жива ли сущность.
        
        Возвращает:
            bool: True, если health > 0.
        """
        return self.health > 0
    
