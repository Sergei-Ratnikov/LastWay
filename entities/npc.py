from entities.person import Person

class NPC(Person):
    """
    Класс неигрового персонажа.
    Наследует свойства Person (и Actor).
    """
    
    def __init__(self, npc_id, name, x, y, dialog_id=None, gender="male"):
        """
        Инициализация NPC.
        
        Аргументы:
            npc_id (str): Уникальный идентификатор NPC.
            name (str): Отображаемое имя.
            x (int): Начальная координата X.
            y (int): Начальная координата Y.
            dialog_id (str): ID диалога для этого NPC.
            gender (str): Пол персонажа.
        """
        # Вызываем конструктор Person
        super().__init__(
            person_id=npc_id,
            name=name,
            x=x,
            y=y,
            gender=gender
        )
        
        # ID диалога (ссылка на JSON-файл диалога)
        self.dialog_id = dialog_id
        
        # Тип движения: "stationary" (стоит), "patrol" (патрулирует), "follow" (следует)
        self.movement = "stationary"
        
        # Задержка между шагами (в миллисекундах)
        self.move_delay_ms = 1000
        
        # Список точек патруля: [(x1, y1), (x2, y2), ...]
        self.patrol_points = []
        
        # Индекс текущей точки патруля
        self.patrol_index = 0
        
        # ID цели для следования (если movement == "follow")
        self.follow_target = None
        
        # Время последнего шага (для задержки движения)
        self.last_move_time = 0
        
        # Время, до которого NPC ждёт (для расхождения с другими NPC)
        self.wait_until = 0
        
        # Позиция последней открытой двери (для закрытия за собой)
        self.last_door_pos = None
        
